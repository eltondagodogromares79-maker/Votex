use std::sync::Arc;

use actix_web::web;
use core_infra::{
    api::middleware::{AuthorizationGuard, JwtAuthentication},
    application::ports::security::TokenAuthenticator,
};

use crate::api::handler::{
    coordinators::{
        add_coordinator, get_coordinator, list_coordinators, remove_coordinator,
        replace_coordinator, resend_coordinator_credentials, update_coordinator,
    },
    pageant_staff::{
        assign_judge, assign_pageant_coordinator, assign_tabulator, list_judges,
        list_pageant_coordinators, list_tabulator, revoke_judge, revoke_pageant_coordinator,
        revoke_tabulator,
    },
    pageants::{archive_pageant, create_pageant, get_pageant, list_pageants, update_pageant},
    subscriptions::{
        cancel as cancel_subscription, current as current_subscription,
        history as subscription_history, plans as subscription_plans, subscribe,
    },
    transactions::history as transaction_history,
    vote_packages::{create, deactivate, list, update},
    vote_revenue::report as vote_revenue_report,
};

/// Register organization-owner routes with authentication and RBAC guards.
pub fn configure(config: &mut web::ServiceConfig, token_validator: Arc<dyn TokenAuthenticator>) {
    config.service(
        web::scope("/api/v1/organizations/{organization_id}")
            .wrap(JwtAuthentication::new(token_validator))
            .service(
                web::resource("/subscription-plans")
                    .wrap(AuthorizationGuard::organization(
                        "billing.read",
                        "organization_id",
                    ))
                    .route(web::get().to(subscription_plans)),
            )
            .service(
                web::resource("/subscription")
                    .wrap(AuthorizationGuard::organization(
                        "billing.read",
                        "organization_id",
                    ))
                    .route(web::get().to(current_subscription)),
            )
            .service(
                web::resource("/subscriptions")
                    .wrap(AuthorizationGuard::organization(
                        "billing.manage",
                        "organization_id",
                    ))
                    .route(web::get().to(subscription_history))
                    .route(web::post().to(subscribe)),
            )
            .service(
                web::resource("/subscriptions/{subscription_id}")
                    .wrap(AuthorizationGuard::organization(
                        "billing.manage",
                        "organization_id",
                    ))
                    .route(web::delete().to(cancel_subscription)),
            )
            .service(
                web::resource("/revenue/votes")
                    .wrap(AuthorizationGuard::organization(
                        "billing.read",
                        "organization_id",
                    ))
                    .route(web::get().to(vote_revenue_report)),
            )
            .service(
                web::resource("/transactions")
                    .wrap(AuthorizationGuard::organization(
                        "billing.read",
                        "organization_id",
                    ))
                    .route(web::get().to(transaction_history)),
            )
            .service(
                web::resource("/pageants")
                    .route(
                        web::post()
                            .to(create_pageant)
                            .wrap(AuthorizationGuard::organization(
                                "pageant.create",
                                "organization_id",
                            )),
                    )
                    .route(
                        web::get()
                            .to(list_pageants)
                            .wrap(AuthorizationGuard::organization(
                                "pageant.read",
                                "organization_id",
                            )),
                    ),
            )
            .service(
                web::resource("/pageants/{pageant_id}")
                    .route(
                        web::get()
                            .to(get_pageant)
                            .wrap(AuthorizationGuard::organization(
                                "pageant.read",
                                "organization_id",
                            )),
                    )
                    .route(
                        web::put()
                            .to(update_pageant)
                            .wrap(AuthorizationGuard::organization(
                                "pageant.update",
                                "organization_id",
                            )),
                    )
                    .route(web::delete().to(archive_pageant).wrap(
                        AuthorizationGuard::organization("pageant.delete", "organization_id"),
                    )),
            )
            .service(
                web::resource("/coordinators")
                    .wrap(AuthorizationGuard::organization(
                        "role.assign",
                        "organization_id",
                    ))
                    .route(web::get().to(list_coordinators))
                    .route(web::post().to(add_coordinator)),
            )
            .service(
                web::resource("/coordinators/{user_id}")
                    .wrap(AuthorizationGuard::organization(
                        "role.assign",
                        "organization_id",
                    ))
                    .route(web::get().to(get_coordinator))
                    .route(web::put().to(replace_coordinator))
                    .route(web::patch().to(update_coordinator))
                    .route(web::delete().to(remove_coordinator)),
            )
            .service(
                web::resource("/coordinators/{user_id}/resend-credentials")
                    .wrap(AuthorizationGuard::organization(
                        "role.assign",
                        "organization_id",
                    ))
                    .route(web::post().to(resend_coordinator_credentials)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/vote-packages")
                    .wrap(AuthorizationGuard::organization(
                        "voting.manage",
                        "organization_id",
                    ))
                    .route(web::get().to(list))
                    .route(web::post().to(create)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/vote-packages/{package_id}")
                    .wrap(AuthorizationGuard::organization(
                        "voting.manage",
                        "organization_id",
                    ))
                    .route(web::put().to(update))
                    .route(web::delete().to(deactivate)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/coordinators")
                    .wrap(AuthorizationGuard::organization(
                        "role.assign",
                        "organization_id",
                    ))
                    .route(web::get().to(list_pageant_coordinators))
                    .route(web::post().to(assign_pageant_coordinator)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/coordinators/{user_id}")
                    .wrap(AuthorizationGuard::organization(
                        "role.assign",
                        "organization_id",
                    ))
                    .route(web::delete().to(revoke_pageant_coordinator)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/judges")
                    .wrap(AuthorizationGuard::organization(
                        "judge.assign",
                        "organization_id",
                    ))
                    .route(web::get().to(list_judges))
                    .route(web::post().to(assign_judge)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/judges/{user_id}")
                    .wrap(AuthorizationGuard::organization(
                        "judge.assign",
                        "organization_id",
                    ))
                    .route(web::delete().to(revoke_judge)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/tabulators")
                    .wrap(AuthorizationGuard::organization(
                        "tabulator.assign",
                        "organization_id",
                    ))
                    .route(web::get().to(list_tabulator))
                    .route(web::post().to(assign_tabulator)),
            )
            .service(
                web::resource("/pageants/{pageant_id}/tabulators/{user_id}")
                    .wrap(AuthorizationGuard::organization(
                        "tabulator.assign",
                        "organization_id",
                    ))
                    .route(web::delete().to(revoke_tabulator)),
            ),
    );
}
