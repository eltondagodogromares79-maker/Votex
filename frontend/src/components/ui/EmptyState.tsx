import { cn } from "@/src/lib/utils";
import { Button } from "./Button";

interface EmptyStateProps {
  /** Icon slot — pass an SVG element */
  icon?: React.ReactNode;
  heading: string;
  description?: string;
  action?: {
    label: string;
    onClick: () => void;
  };
  className?: string;
}

export function EmptyState({
  icon,
  heading,
  description,
  action,
  className,
}: EmptyStateProps) {
  return (
    <div
      className={cn(
        "flex flex-col items-center justify-center text-center py-16 px-6",
        className,
      )}
    >
      {icon && (
        <div className="mb-4 text-muted/50 w-12 h-12">{icon}</div>
      )}
      <h3 className="text-h3 text-charcoal mb-2">{heading}</h3>
      {description && (
        <p className="text-body text-muted max-w-sm mb-6">{description}</p>
      )}
      {action && (
        <Button variant="primary" size="md" onClick={action.onClick}>
          {action.label}
        </Button>
      )}
    </div>
  );
}

